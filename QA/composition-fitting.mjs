import assert from 'node:assert/strict';
import {ContentFitter} from '../CORE/ContentFitter.mjs';
import {selectComposition} from '../COMPOSITIONS/registry.mjs';
import {ContentInventory} from '../CORE/ContentInventory.mjs';
import {AnimationAdvisor} from '../CORE/AnimationAdvisor.mjs';
const points=Array.from({length:3},(_,i)=>({title:'Point '+i,text:'Supporting detail.'}));
assert.equal(selectComposition({title:'Unrelated title',intent:'evidence',items:points}),'spotlight');
assert.equal(selectComposition({title:'Unreasonable',items:points}),null);
assert.equal(selectComposition({title:'Overview and evidence',items:points},{previousPattern:'editorial-split'}),'spotlight');
assert.equal(selectComposition({composition:'checklist',intent:'evidence',items:points}),'checklist');
assert.equal(selectComposition({intent:'decision',items:[{id:'root',title:'Start'},{id:'yes',parent:'root',title:'Proceed'}]}),'decision-tree');
assert.equal(selectComposition({intent:'decision',items:[{id:'root',parent:'absent'}]}),null);
assert.equal(selectComposition({kind:'opening',intent:'evidence',items:points}),null);
assert.equal(selectComposition({intent:'compare',items:Array.from({length:4},()=>({title:'Side'}))}),null);
const inventory=new ContentInventory().build({title:'Example',sections:[{title:'Result',intent:'evidence',items:points}]});
assert.equal(inventory.blocks.find(b=>b.kind==='section').intent,'evidence');
const branching=new ContentInventory().build({title:'Decision',sections:[{title:'Choose',intent:'decision',items:[{id:'root',title:'Assess'},{id:'yes',parent:'root',title:'Yes'},{id:'no',parent:'root',title:'No'}]}]});
const branch=branching.blocks.find(b=>b.kind==='section');
assert.equal(branch.items.length,3);
assert.equal(selectComposition(branch),'decision-tree');
const cards=Array.from({length:10},(_,i)=>({title:'Unique '+i,text:'All original text '+i,detail:'Detail '+i}));
const source={title:'Fit',theme:'auto',slides:[{id:'dense',components:[{id:'cards',type:'GlassCard',data:{title:'Dense',cards,note:'Final note'}}],animations:[]},{id:'dense-part-2',components:[{type:'ClosingScene',data:{title:'Close'}}]}]};
const before=JSON.stringify(source),fit=new ContentFitter(),result=fit.apply(source,{mode:'split'});
const animated=structuredClone(source);animated.slides[0].animations=new AnimationAdvisor().forComponent('GlassCard');
assert.equal(fit.apply(animated,{mode:'split'}).schema.slides.length,4);
assert.equal(JSON.stringify(source),before);
assert.deepEqual(result.schema.slides.flatMap(s=>s.components[0].data.cards||[]),cards);
assert.equal(new Set(result.schema.slides.map(s=>s.id)).size,result.schema.slides.length);
assert.equal(result.schema.slides.filter(s=>s.components[0].data.note).length,1);
assert.deepEqual(fit.apply(source).schema,source);
assert.throws(()=>fit.apply(source,{mode:'typo'}),/contentFit/);
const custom=structuredClone(source);custom.slides[0].animations=[{target:'#cards',type:'fade'}];
assert.equal(fit.apply(custom,{mode:'split'}).schema.slides.length,2);
assert.deepEqual(fit.apply(result.schema,{mode:'split'}).schema,result.schema);
console.log('Composition/fitting: semantic selection, capacity, topology, preservation, IDs, opt-in and idempotence passed.');
