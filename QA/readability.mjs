import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {renderComponent} from '../BUILDER/lib/component-renderer.mjs';
const V10={classes:{}};
for(const name of ['SlideManager','ChartController'])vm.runInNewContext(fs.readFileSync(new URL(`../RUNTIME/${name}.js`,import.meta.url),'utf8'),{window:{V10Engine:V10}});
const rect=(top,bottom)=>({getBoundingClientRect:()=>({top,bottom,height:bottom-top})});
const slides=[rect(-1200,100),rect(100,1600),rect(1600,2200)];
const manager={stage:{clientHeight:844,getBoundingClientRect:()=>({top:0})},slides};
assert.equal(V10.classes.SlideManager.prototype.nearest.call(manager),slides[1]);
slides[1]=rect(-700,800);slides[2]=rect(800,1400);
assert.equal(V10.classes.SlideManager.prototype.nearest.call(manager),slides[1]);
const fit=V10.classes.ChartController.prototype.fitLabel,ctx={measureText:s=>({width:s.length*7})};
assert.equal(fit(ctx,'Short',100),'Short');
const long=fit(ctx,'Emergency observation unit',84);
assert.ok(long.endsWith('…'));assert.ok(ctx.measureText(long).width<=84);
const html=renderComponent({type:'Charts',data:{charts:[{title:'Comparison',chartType:'line',series:[{name:'A long planned demand label',values:[1,2]},{name:'Observed demand',values:[2,3]}]}]}},0);
assert.match(html,/v135-chart-legend/);assert.match(html,/A long planned demand label/);assert.match(html,/domLegend/);
console.log('Readability: long-slide selection, bounded chart labels and semantic legends passed.');
